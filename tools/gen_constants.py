#!/usr/bin/env python3
"""Code generator: emits protocol constants for Go from docs/protocol-constants.json.
Ensures single source of truth as required by PROTOCOL.md.
"""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC_FILE = ROOT / "docs" / "protocol-constants.json"
OUT_GO = ROOT / "core" / "protocol" / "constants.go"


def to_pascal(s: str) -> str:
    parts = s.split("_")
    res = []
    for p in parts:
        p_lower = p.lower()
        if p_lower == "ms":
            res.append("Ms")
        elif p_lower == "ttl":
            res.append("TTL")
        elif p_lower == "s":
            res.append("Sec")
        elif p_lower == "ip":
            res.append("IP")
        elif p_lower == "qr":
            res.append("QR")
        elif p_lower == "fs":
            res.append("FS")
        elif p_lower == "uri":
            res.append("URI")
        else:
            res.append(p.capitalize())
    return "".join(res)


def main():
    with open(SPEC_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)

    constants = data["constants"]
    frame_types = data["frame_types"]
    error_codes = data["error_codes"]
    local_errors = data.get("local_error_codes", [])

    lines = [
        "// Code generated by tools/gen_constants.py from docs/protocol-constants.json. DO NOT EDIT.",
        "",
        "package protocol",
        "",
        "// Wire and engine constants",
        "const (",
    ]

    for k, info in constants.items():
        name = to_pascal(k)
        val = info["value"]
        note = info.get("note", "")
        unit = info.get("unit", "")
        comment = f" // {val} {unit}" if unit else ""
        if note:
            comment = f"{comment} - {note}" if comment else f" // {note}"

        if isinstance(val, str):
            lines.append(f'\t{name} = "{val}"{comment}')
        elif isinstance(val, int):
            lines.append(f"\t{name} = {val}{comment}")
        else:
            lines.append(f"\t{name} = {val}{comment}")

    lines.append(")")
    lines.append("")

    # Frame types
    lines.append("// FrameType identifies a wire frame type byte")
    lines.append("type FrameType uint8")
    lines.append("")
    lines.append("const (")
    for k, val in frame_types.items():
        name = "Frame" + to_pascal(k)
        lines.append(f"\t{name} FrameType = {val}")
    lines.append(")")
    lines.append("")

    # FrameType String helper
    lines.append("func (f FrameType) String() string {")
    lines.append("\tswitch f {")
    for k, val in frame_types.items():
        name = "Frame" + to_pascal(k)
        lines.append(f'\tcase {name}: return "{k}"')
    lines.append('\tdefault: return "UNKNOWN"')
    lines.append("\t}")
    lines.append("}")
    lines.append("")

    # Error codes
    lines.append("// WireErrorCode identifies wire error codes in ERROR frames")
    lines.append("type WireErrorCode uint8")
    lines.append("")
    lines.append("const (")
    for k, val in error_codes.items():
        name = "ErrCode" + to_pascal(k)
        lines.append(f"\t{name} WireErrorCode = {val}")
    lines.append(")")
    lines.append("")

    lines.append("func (e WireErrorCode) String() string {")
    lines.append("\tswitch e {")
    for k, val in error_codes.items():
        name = "ErrCode" + to_pascal(k)
        lines.append(f'\tcase {name}: return "{k}"')
    lines.append('\tdefault: return "UNKNOWN_ERROR"')
    lines.append("\t}")
    lines.append("}")
    lines.append("")

    # Local error codes
    lines.append("// Local error codes used internally/in diagnostics")
    lines.append("const (")
    for code in local_errors:
        name = "LocalErr" + to_pascal(code)
        lines.append(f'\t{name} = "{code}"')
    lines.append(")")
    lines.append("")

    OUT_GO.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_GO, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {OUT_GO}")

    # Generate Kotlin Constants
    OUT_KT = ROOT / "android" / "app" / "src" / "main" / "kotlin" / "com" / "example" / "lanvault" / "protocol" / "Constants.kt"
    kt_lines = [
        "// Code generated by tools/gen_constants.py from docs/protocol-constants.json. DO NOT EDIT.",
        "",
        "package com.example.lanvault.protocol",
        "",
        "object Constants {",
    ]

    for k, info in constants.items():
        val = info["value"]
        if isinstance(val, str):
            kt_lines.append(f'    const val {k}: String = "{val}"')
        elif isinstance(val, int):
            kt_lines.append(f'    const val {k}: Long = {val}L')

    kt_lines.append("")
    kt_lines.append("    // Frame Types")
    for k, val in frame_types.items():
        kt_lines.append(f'    const val FRAME_{k}: Byte = {val}.toByte()')

    kt_lines.append("")
    kt_lines.append("    // Error Codes")
    for k, val in error_codes.items():
        kt_lines.append(f'    const val ERR_{k}: Int = {val}')

    kt_lines.append("}")
    kt_lines.append("")

    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_KT, "w", encoding="utf-8") as f:
        f.write("\n".join(kt_lines))
    print(f"Generated {OUT_KT}")


if __name__ == "__main__":
    main()
