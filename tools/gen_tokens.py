#!/usr/bin/env python3
"""Code generator: emits CSS variables and TypeScript constants from docs/design-tokens.json and docs/protocol-constants.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS_FILE = ROOT / "docs" / "design-tokens.json"
CONSTANTS_FILE = ROOT / "docs" / "protocol-constants.json"

OUT_CSS = ROOT / "desktop" / "frontend" / "src" / "styles" / "tokens.css"
OUT_TS = ROOT / "desktop" / "frontend" / "src" / "types" / "tokens.ts"
OUT_CONSTANTS_TS = ROOT / "desktop" / "frontend" / "src" / "types" / "protocol.ts"


def token_to_css_var(name: str) -> str:
    return "--" + name.replace(".", "-")


def main():
    with open(TOKENS_FILE, "r", encoding="utf-8") as f:
        tokens = json.load(f)

    with open(CONSTANTS_FILE, "r", encoding="utf-8") as f:
        constants = json.load(f)

    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)
    OUT_TS.parent.mkdir(parents=True, exist_ok=True)

    # Generate CSS variables
    css_lines = [
        "/* Generated by tools/gen_tokens.py from docs/design-tokens.json. DO NOT EDIT. */",
        "",
        ":root {",
    ]

    # Shared radii, motion, spacing
    for rad, val in tokens.get("radius", {}).items():
        css_lines.append(f"  --radius-{rad}: {val}px;")

    for i, s in enumerate(tokens.get("spacing", [])):
        css_lines.append(f"  --space-{i}: {s}px;")

    motion = tokens.get("motion", {})
    css_lines.append(f"  --motion-micro: {motion.get('micro_ms', 120)}ms;")
    css_lines.append(f"  --motion-panel: {motion.get('panel_ms', 200)}ms;")
    css_lines.append(f"  --motion-page: {motion.get('page_ms', 300)}ms;")
    easing = motion.get("easing", [0.2, 0, 0, 1])
    css_lines.append(f"  --motion-easing: cubic-bezier({easing[0]}, {easing[1]}, {easing[2]}, {easing[3]});")

    # Light mode defaults
    css_lines.append("")
    css_lines.append("  /* Light theme colors (default) */")
    for key, val in tokens["color"]["light"].items():
        css_lines.append(f"  {token_to_css_var(key)}: {val};")
    css_lines.append("}")
    css_lines.append("")

    # Dark mode
    css_lines.append("/* Dark theme */")
    css_lines.append("html.dark, [data-theme='dark'] {")
    for key, val in tokens["color"]["dark"].items():
        css_lines.append(f"  {token_to_css_var(key)}: {val};")
    css_lines.append("}")
    css_lines.append("")

    with open(OUT_CSS, "w", encoding="utf-8") as f:
        f.write("\n".join(css_lines))
    print(f"Generated {OUT_CSS}")

    # Generate TypeScript tokens
    ts_lines = [
        "// Generated by tools/gen_tokens.py. DO NOT EDIT.",
        "",
        "export const designTokens = " + json.dumps(tokens, indent=2) + " as const;",
        "",
        "export type DesignTokens = typeof designTokens;",
    ]
    with open(OUT_TS, "w", encoding="utf-8") as f:
        f.write("\n".join(ts_lines))
    print(f"Generated {OUT_TS}")

    # Generate TypeScript protocol constants and types
    ts_proto_lines = [
        "// Generated by tools/gen_tokens.py from docs/protocol-constants.json. DO NOT EDIT.",
        "",
        "export const ProtocolConstants = {",
    ]
    for k, v in constants["constants"].items():
        val = v["value"]
        if isinstance(val, str):
            ts_proto_lines.append(f'  {k}: "{val}",')
        else:
            ts_proto_lines.append(f"  {k}: {val},")
    ts_proto_lines.append("} as const;")
    ts_proto_lines.append("")

    ts_proto_lines.append("export const FrameTypes = {")
    for k, v in constants["frame_types"].items():
        ts_proto_lines.append(f"  {k}: {v},")
    ts_proto_lines.append("} as const;")
    ts_proto_lines.append("export type FrameType = typeof FrameTypes[keyof typeof FrameTypes];")
    ts_proto_lines.append("")

    ts_proto_lines.append("export const ErrorCodes = {")
    for k, v in constants["error_codes"].items():
        ts_proto_lines.append(f"  {k}: {v},")
    ts_proto_lines.append("} as const;")
    ts_proto_lines.append("export type ErrorCode = typeof ErrorCodes[keyof typeof ErrorCodes];")
    ts_proto_lines.append("")

    ts_proto_lines.append("export const LocalErrorCodes = [")
    for code in constants.get("local_error_codes", []):
        ts_proto_lines.append(f'  "{code}",')
    ts_proto_lines.append("] as const;")
    ts_proto_lines.append("export type LocalErrorCode = typeof LocalErrorCodes[number];")
    ts_proto_lines.append("")

    with open(OUT_CONSTANTS_TS, "w", encoding="utf-8") as f:
        f.write("\n".join(ts_proto_lines))
    print(f"Generated {OUT_CONSTANTS_TS}")


if __name__ == "__main__":
    main()
